class Solution:
    def nthSuperUglyNumber(self, n: int, primes: list[int]) -> int:
        if n == 1:
            return 1

        ugly_numbers = [1]
        
        # Min-heap to store (next_ugly_candidate, prime_index, ugly_number_index).
        # prime_index: index of the prime in the 'primes' list.
        # ugly_number_index: index of the ugly number in the 'ugly_numbers' list
        #                    that was used to generate this candidate.
        # This tuple structure allows the heap to correctly sort by the candidate value.
        import heapq
        min_heap = []

        # Initialize the heap with the first candidate for each prime.
        # Each prime `p` initially considers `p * ugly_numbers[0]` (which is `p * 1`).
        for i in range(len(primes)):
            heapq.heappush(min_heap, (primes[i], i, 0))

        # Generate n-1 additional super ugly numbers.
        # The loop continues until 'ugly_numbers' contains 'n' elements.
        while len(ugly_numbers) < n:
            # Extract the smallest candidate from the heap.
            val, prime_idx, ugly_idx = heapq.heappop(min_heap)

            # If this value is different from the last super ugly number added,
            # it means we've found a new, unique super ugly number.
            # This check handles duplicates (e.g., 2*3 and 3*2 both result in 6).
            if val != ugly_numbers[-1]:
                ugly_numbers.append(val)
            
            # Always push the next candidate generated by the current prime_idx.
            # The next candidate is primes[prime_idx] multiplied by the next
            # available ugly number in the 'ugly_numbers' sequence.
            # ugly_numbers[ugly_idx + 1] refers to the next ugly number that
            # primes[prime_idx] should multiply to generate its next candidate.
            heapq.heappush(min_heap, (primes[prime_idx] * ugly_numbers[ugly_idx + 1], prime_idx, ugly_idx + 1))
        
        # The nth super ugly number is the last one in our generated list.
        return ugly_numbers[-1]